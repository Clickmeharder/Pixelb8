function normalMazeIndexForLevel(level) {
    let normalIndex = -1;
    for (let layer = 1; layer <= level; layer++) {
        if (determineMode(layer) === "normal") normalIndex++;
    }
    return Math.max(0, normalIndex);
}

function presetForLevel(level) {
    const sequenceIndex = normalMazeIndexForLevel(level) % MAZE_SEQUENCE.length;
    const presetKey = MAZE_SEQUENCE[sequenceIndex];
    const preset = MAZE_PRESETS[presetKey];
    if (!preset) throw new Error(`Unknown maze preset "${presetKey}" in MAZE_SEQUENCE.`);
    return preset;
}

function parseEditableLayout(mapData, name) {
    if (mapData.length !== ROWS) {
        throw new Error(`${name} must have ${ROWS} rows; found ${mapData.length}.`);
    }

    const tileValues = new Map([
        ["#", WALL],
        [0, DOT],
        [2, POWER],
        [3, EMPTY],
        [4, SPECTRE_HOME],
        [5, SPECTRE_GATE]
    ]);

    return mapData.map((row, rowIndex) => {
        if (row.length !== COLS) {
            throw new Error(`${name} row ${rowIndex + 1} must contain ${COLS} entries; found ${row.length}.`);
        }

        return row.map(tile => {
            if (!tileValues.has(tile)) {
                throw new Error(`${name} contains invalid map tile "${tile}".`);
            }

            return tileValues.get(tile);
        });
    });
}

function loadPresetMaze(level) {
    const preset = presetForLevel(level);
    currentTheme = MAZE_THEMES[preset.theme] || MAZE_THEMES[0];
    currentMazeName = preset.name;
    return parseEditableLayout(preset.mapData, preset.name);
}

function nearestOpen(map, targetX, targetY) {
    let best = null;
    let bestDistance = Infinity;
    for (let y = 1; y < ROWS - 1; y++) {
        for (let x = 1; x < COLS - 1; x++) {
            if (
                map[y][x] === WALL ||
                map[y][x] === SPECTRE_HOME ||
                map[y][x] === SPECTRE_GATE
            ) continue;
            const distance = Math.abs(x - targetX) + Math.abs(y - targetY);
            if (distance < bestDistance) {
                best = { x, y };
                bestDistance = distance;
            }
        }
    }
    return best || { x: 1, y: 1 };
}

function openTiles(minimumFromPlayer = 0) {
    const tiles = [];
    for (let y = 1; y < ROWS - 1; y++) {
        for (let x = 1; x < COLS - 1; x++) {
            if (
                currentMap[y][x] === WALL ||
                currentMap[y][x] === SPECTRE_HOME ||
                currentMap[y][x] === SPECTRE_GATE
            ) continue;
            if (Math.abs(x - playerSpawn.x) + Math.abs(y - playerSpawn.y) < minimumFromPlayer) continue;
            tiles.push({ x, y });
        }
    }
    return shuffle(tiles);
}

function initNormalLevel(entry) {
    currentMap = parseEditableLayout(entry.mapData, entry.name);
    playerSpawn = nearestOpen(currentMap, 13, 27);
    totalPellets = 0;
    pelletsEaten = 0;
    currentMap.forEach(row => row.forEach(tile => {
        if (tile === DOT || tile === POWER) totalPellets++;
    }));

    const levelBoost = Math.min(.34, (currentLevel - 1) * .025);
    const spawnTargets = [
        { x: 13, y: 14 }, { x: 11, y: 15 }, { x: 16, y: 15 },
        { x: 13, y: 11 }, { x: 8, y: 14 }, { x: 19, y: 14 }
    ];
    enemies = Array.from({ length: config.enemyCount }, (_, index) => {
        const spawn = nearestOpen(currentMap, spawnTargets[index].x, spawnTargets[index].y);
        return makeSpectre(index, spawn, config.enemySpeed + levelBoost, index * config.releaseGap);
    });
}

function initChallengeLevel(entry) {
    const settings = entry.settings || {};
    const type = settings.challengeType || "PEC RUSH";
    currentMap = parseEditableLayout(entry.mapData, entry.name);
    playerSpawn = nearestOpen(currentMap, 13, 27);
    const counts = { "PEC RUSH": 14, "SIGNAL CHAIN": 8, "DRONE HEIST": 10 };
    const points = { "PEC RUSH": 200, "SIGNAL CHAIN": 350, "DRONE HEIST": 300 };
    challenge = {
        type,
        time: (settings.timeSeconds || config.challengeSeconds) * 60,
        totalTime: (settings.timeSeconds || config.challengeSeconds) * 60,
        collected: 0,
        required: settings.required || counts[type] || 10,
        itemPoints: settings.itemPoints || points[type] || 250,
        items: [],
        hitFlash: 0
    };
    challenge.items = openTiles(5).slice(0, challenge.required).map((tile, index) => ({
        ...tile, collected: false, order: index
    }));

    let hazardCount = Number.isFinite(settings.hazards) ? settings.hazards : config.challengeHazards;
    if (type === "SIGNAL CHAIN") hazardCount = Math.max(0, hazardCount - 1);
    if (type === "DRONE HEIST") hazardCount++;
    const hazardSpawns = openTiles(10);
    enemies = Array.from({ length: hazardCount }, (_, index) => {
        return makeSpectre(index + 2, hazardSpawns[index], config.enemySpeed * .82, index * 50);
    });
}

function initBossLevel(entry) {
    const settings = entry.settings || {};
    currentMap = parseEditableLayout(entry.mapData, entry.name);
    playerSpawn = nearestOpen(currentMap, 13, 27);
    const spawn = nearestOpen(currentMap, 13, 15);
    const extraHp = settings.hpBonus || 0;
    const hp = config.bossHp + extraHp;
    boss = {
        x: spawn.x * TILE, y: spawn.y * TILE,
        dirX: 1, dirY: 0, speed: config.bossSpeed * (settings.speedScale || 1),
        hp, maxHp: hp,
        shield: true, nodesNeeded: settings.nodes || config.bossNodes, nodesCollected: 0,
        nodes: [], vulnerableTimer: 0,
        shotInterval: config.bossShot * (settings.shotScale || 1),
        shotCooldown: config.bossShot * (settings.shotScale || 1),
        projectiles: [], turnLock: 0, contactCooldown: 0
    };
    spawnBossNodes();
}

function makeSpectre(index, spawn, speed, releaseTimer = 0) {
    return {
        x: spawn.x * TILE, y: spawn.y * TILE,
        dirX: index % 2 ? -1 : 1, dirY: 0,
        speed, color: SPECTRE_COLORS[index % SPECTRE_COLORS.length],
        behavior: index % 4, releaseTimer, turnLock: 0, spawn
    };
}

function spawnBossNodes() {
    const candidates = openTiles(8).filter(tile => {
        const bossTileX = Math.floor(boss.x / TILE);
        const bossTileY = Math.floor(boss.y / TILE);
        return Math.abs(tile.x - bossTileX) + Math.abs(tile.y - bossTileY) > 7;
    });
    boss.nodes = candidates.slice(0, boss.nodesNeeded).map(tile => ({ ...tile, collected: false }));
    boss.nodesCollected = 0;
}

function resetPlayer(keepInvulnerability = false) {
    player.x = playerSpawn.x * TILE;
    player.y = playerSpawn.y * TILE;
    player.dirX = 0;
    player.dirY = 0;
    player.nextDirX = 0;
    player.nextDirY = 0;
    if (keepInvulnerability) player.invulnerable = Math.max(player.invulnerable, 100);
}

function tileAtPixel(x, y) {
    const col = Math.floor(x / TILE);
    const row = Math.floor(y / TILE);
    if (row < 0 || row >= ROWS || col < 0 || col >= COLS) return EMPTY;
    return currentMap[row][col];
}

function collidesWithWall(x, y, allowSpectreTiles = false) {
    const inset = 3;
    const points = [
        [x + inset, y + inset], [x + TILE - inset, y + inset],
        [x + inset, y + TILE - inset], [x + TILE - inset, y + TILE - inset]
    ];

    return points.some(([px, py]) => {
        const tile = tileAtPixel(px, py);
        if (tile === WALL) return true;
        if (!allowSpectreTiles && (tile === SPECTRE_HOME || tile === SPECTRE_GATE)) return true;
        return false;
    });
}

function canMove(entity, dx, dy, distance = entity.speed) {
    return !collidesWithWall(
        entity.x + dx * distance,
        entity.y + dy * distance,
        entity !== player
    );
}

function nearGrid(value, tolerance = 2.2) {
    const remainder = ((value % TILE) + TILE) % TILE;
    return remainder < tolerance || TILE - remainder < tolerance;
}

function snapGrid(value) {
    return Math.round(value / TILE) * TILE;
}

function wrapEntity(entity) {
    if (entity.x < -TILE) entity.x = canvas.width - 1;
    if (entity.x > canvas.width) entity.x = -TILE + 1;
}

function movePlayer() {
    if (player.nextDirX && nearGrid(player.y, player.speed + .3)) {
        const alignedY = snapGrid(player.y);
        if (!collidesWithWall(player.x + player.nextDirX * player.speed, alignedY)) {
            player.y = alignedY;
            player.dirX = player.nextDirX;
            player.dirY = 0;
        }
    } else if (player.nextDirY && nearGrid(player.x, player.speed + .3)) {
        const alignedX = snapGrid(player.x);
        if (!collidesWithWall(alignedX, player.y + player.nextDirY * player.speed)) {
            player.x = alignedX;
            player.dirX = 0;
            player.dirY = player.nextDirY;
        }
    }

    if (canMove(player, player.dirX, player.dirY)) {
        player.x += player.dirX * player.speed;
        player.y += player.dirY * player.speed;
    }
    wrapEntity(player);
}

function validDirections(entity) {
    let valid = DIRS.filter(direction => canMove(entity, direction.x, direction.y, entity.speed + 1));
    const nonReverse = valid.filter(direction => (
        direction.x !== -entity.dirX || direction.y !== -entity.dirY
    ));
    if (nonReverse.length) valid = nonReverse;
    return valid;
}

function enemyTarget(enemy) {
    const playerX = player.x;
    const playerY = player.y;
    if (enemy.behavior === 1) {
        return { x: playerX + player.dirX * TILE * 4, y: playerY + player.dirY * TILE * 4 };
    }
    if (enemy.behavior === 2) {
        return { x: canvas.width - playerX, y: canvas.height - playerY };
    }
    if (enemy.behavior === 3) {
        return player.powerTimer > 0 ? { x: canvas.width / 2, y: canvas.height / 2 } : { x: playerX, y: playerY };
    }
    return { x: playerX, y: playerY };
}

function chooseDirection(entity, target, chaseChance = config.chase) {
    const valid = validDirections(entity);
    if (!valid.length) return { x: -entity.dirX, y: -entity.dirY };
    const frightened = player.powerTimer > 0 && mode === "normal";
    valid.sort((a, b) => {
        const distanceA = Math.hypot(entity.x + a.x * TILE - target.x, entity.y + a.y * TILE - target.y);
        const distanceB = Math.hypot(entity.x + b.x * TILE - target.x, entity.y + b.y * TILE - target.y);
        return frightened ? distanceB - distanceA : distanceA - distanceB;
    });
    if (frightened || rng() < chaseChance) return valid[0];
    return valid[Math.floor(rng() * valid.length)];
}

function moveSpectre(enemy) {
    if (enemy.releaseTimer > 0) {
        enemy.releaseTimer--;
        return;
    }
    if (enemy.turnLock > 0) enemy.turnLock--;
    if (nearGrid(enemy.x, enemy.speed + .25) && nearGrid(enemy.y, enemy.speed + .25)) {
        enemy.x = snapGrid(enemy.x);
        enemy.y = snapGrid(enemy.y);
        const valid = validDirections(enemy);
        const blocked = !canMove(enemy, enemy.dirX, enemy.dirY, enemy.speed + 1);
        if (blocked || (enemy.turnLock <= 0 && valid.length > 1)) {
            const direction = chooseDirection(enemy, enemyTarget(enemy));
            enemy.dirX = direction.x;
            enemy.dirY = direction.y;
            enemy.turnLock = 7;
        }
    }
    if (canMove(enemy, enemy.dirX, enemy.dirY)) {
        const frightenedScale = player.powerTimer > 0 && mode === "normal" ? .74 : 1;
        enemy.x += enemy.dirX * enemy.speed * frightenedScale;
        enemy.y += enemy.dirY * enemy.speed * frightenedScale;
    }
    wrapEntity(enemy);
}

function update() {
    if (!gameRunning || gameOver) return;
    if (player.invulnerable > 0) player.invulnerable--;
    if (player.powerTimer > 0) player.powerTimer--;
    if (tiltActive && --tiltTimer <= 0) {
        tiltActive = false;
        cabinet.classList.remove("tilt-active");
    }

    movePlayer();
    if (mode === "normal") updateNormal();
    else if (mode === "challenge") updateChallenge();
    else updateBoss();
}

function playerTile() {
    return {
        x: Math.floor((player.x + TILE / 2) / TILE),
        y: Math.floor((player.y + TILE / 2) / TILE)
    };
}

function updateNormal() {
    const tile = playerTile();
    if (tile.y >= 0 && tile.y < ROWS && tile.x >= 0 && tile.x < COLS) {
        const value = currentMap[tile.y][tile.x];
        if (value === DOT || value === POWER) {
            currentMap[tile.y][tile.x] = EMPTY;
            pelletsEaten++;
            score += value === POWER ? 100 : 10;
            if (value === POWER) {
                player.powerTimer = config.powerTime;
                playBeep(820, .18, "triangle");
            } else {
                playBeep(520 + pelletsEaten % 2 * 60, .025, "sine", .018);
            }
            if (pelletsEaten >= totalPellets) {
                advanceLevel("GRID PURGED");
                return;
            }
        }
    }

    if (!tiltActive) enemies.forEach(moveSpectre);
    checkSpectreCollisions(false);
}

function updateChallenge() {
    if (--challenge.time <= 0) {
        finishChallenge(false);
        return;
    }
    if (challenge.hitFlash > 0) challenge.hitFlash--;

    challenge.items.forEach(item => {
        if (item.collected) return;
        if (challenge.type === "SIGNAL CHAIN" && item.order !== challenge.collected) return;
        const distance = Math.hypot(
            player.x + TILE / 2 - (item.x * TILE + TILE / 2),
            player.y + TILE / 2 - (item.y * TILE + TILE / 2)
        );
        if (distance < 12) {
            item.collected = true;
            challenge.collected++;
            score += challenge.itemPoints;
            playBeep(650 + challenge.collected * 35, .09, "triangle");
            if (challenge.collected >= challenge.required) finishChallenge(true);
        }
    });

    if (!tiltActive) enemies.forEach(moveSpectre);
    checkSpectreCollisions(true);
}

function checkSpectreCollisions(isChallenge) {
    enemies.forEach(enemy => {
        if (enemy.releaseTimer > 0) return;
        const distance = Math.hypot(player.x - enemy.x, player.y - enemy.y);
        if (distance >= 12) return;
        if (isChallenge) {
            challengeHit();
        } else if (player.powerTimer > 0) {
            score += 250;
            const spawn = nearestOpen(currentMap, 13, 15);
            enemy.x = spawn.x * TILE;
            enemy.y = spawn.y * TILE;
            enemy.releaseTimer = 90;
            playBeep(230, .18, "sawtooth");
        } else {
            hitPlayer();
        }
    });
}

function challengeHit() {
    if (player.invulnerable > 0 || !gameRunning) return;
    challenge.time = Math.max(1, challenge.time - 180);
    challenge.hitFlash = 25;
    score = Math.max(0, score - 100);
    player.invulnerable = 150;
    resetPlayer(true);
    playBeep(140, .28, "sawtooth");
}

function finishChallenge(completed) {
    if (!gameRunning) return;
    const timeBonus = completed ? Math.ceil(challenge.time / 60) * 50 : 0;
    score += timeBonus;
    const missed = challenge.required - challenge.collected;
    missedPointsText.textContent = completed
        ? `PERFECT! TIME BONUS +${timeBonus}`
        : `TIME UP · ${challenge.collected}/${challenge.required} CACHE ITEMS · ${missed} MISSED`;
    advanceLevel(completed ? "BONUS CACHE CLEARED" : "BONUS TIMER EXPIRED");
}

function updateBoss() {
    if (boss.contactCooldown > 0) boss.contactCooldown--;
    if (boss.vulnerableTimer > 0 && --boss.vulnerableTimer <= 0) {
        boss.shield = true;
        spawnBossNodes();
        playBeep(180, .2, "sawtooth");
    }

    boss.nodes.forEach(node => {
        if (node.collected || !boss.shield) return;
        const distance = Math.hypot(
            player.x + 8 - (node.x * TILE + 8),
            player.y + 8 - (node.y * TILE + 8)
        );
        if (distance < 12) {
            node.collected = true;
            boss.nodesCollected++;
            score += 300;
            playBeep(650 + boss.nodesCollected * 120, .16, "triangle");
            if (boss.nodesCollected >= boss.nodesNeeded) {
                boss.shield = false;
                boss.vulnerableTimer = config.vulnerable;
                playBeep(1100, .4, "sine");
            }
        }
    });

    if (!tiltActive) {
        moveBoss();
        updateBossProjectiles();
    }

    const contactDistance = Math.hypot(player.x - boss.x, player.y - boss.y);
    if (contactDistance < 18 && boss.contactCooldown <= 0) {
        if (boss.shield) {
            hitPlayer();
            boss.contactCooldown = 90;
        } else {
            boss.hp--;
            score += 1200;
            boss.contactCooldown = 120;
            boss.shield = true;
            boss.vulnerableTimer = 0;
            resetPlayer(true);
            player.invulnerable = 130;
            playBeep(980, .45, "sine");
            if (boss.hp <= 0) {
                score += 5000;
                player.lives = Math.min(config.lives, player.lives + 1);
                advanceLevel("DECAY CORE DESTROYED");
            } else {
                spawnBossNodes();
            }
        }
    }
}

function moveBoss() {
    if (boss.turnLock > 0) boss.turnLock--;
    if (nearGrid(boss.x, boss.speed + .3) && nearGrid(boss.y, boss.speed + .3)) {
        boss.x = snapGrid(boss.x);
        boss.y = snapGrid(boss.y);
        const blocked = !canMove(boss, boss.dirX, boss.dirY, boss.speed + 1);
        if (blocked || boss.turnLock <= 0) {
            const direction = chooseDirection(boss, { x: player.x, y: player.y }, Math.min(.9, config.chase + .1));
            boss.dirX = direction.x;
            boss.dirY = direction.y;
            boss.turnLock = 10;
        }
    }
    if (canMove(boss, boss.dirX, boss.dirY)) {
        boss.x += boss.dirX * boss.speed;
        boss.y += boss.dirY * boss.speed;
    }
    wrapEntity(boss);

    if (--boss.shotCooldown <= 0) {
        boss.shotCooldown = boss.shotInterval;
        const dx = player.x - boss.x;
        const dy = player.y - boss.y;
        const length = Math.hypot(dx, dy) || 1;
        boss.projectiles.push({
            x: boss.x + 8, y: boss.y + 8,
            vx: dx / length * config.projectileSpeed,
            vy: dy / length * config.projectileSpeed,
            warning: config.telegraph, targetX: player.x + 8, targetY: player.y + 8
        });
        playBeep(310, .08, "sawtooth");
    }
}

function updateBossProjectiles() {
    for (let index = boss.projectiles.length - 1; index >= 0; index--) {
        const projectile = boss.projectiles[index];
        if (projectile.warning > 0) {
            projectile.warning--;
            continue;
        }
        projectile.x += projectile.vx;
        projectile.y += projectile.vy;
        if (
            projectile.x < 0 || projectile.x > canvas.width ||
            projectile.y < 0 || projectile.y > canvas.height ||
            tileAtPixel(projectile.x, projectile.y) === WALL
        ) {
            boss.projectiles.splice(index, 1);
            continue;
        }
        if (Math.hypot(player.x + 8 - projectile.x, player.y + 8 - projectile.y) < 10) {
            boss.projectiles.splice(index, 1);
            hitPlayer();
        }
    }
}

function hitPlayer() {
    if (player.invulnerable > 0 || !gameRunning) return;
    player.lives--;
    player.powerTimer = 0;
    playBeep(120, .38, "sawtooth");
    if (player.lives <= 0) {
        triggerGameOver();
        return;
    }
    resetPlayer();
    player.invulnerable = config.invulnerable;
}

function advanceLevel(reason) {
    if (!gameRunning) return;
    gameRunning = false;
    transitioning = true;
    const nextIndex = activeRun.index + 1;
    if (nextIndex >= activeRun.levels.length) {
        transitioning = false;
        if (activeRun.kind === "story") localStorage.setItem("decguy_story_progress", "0");
        document.getElementById("run-complete-title").textContent = activeRun.kind === "story" ? "STORY COMPLETE" : "RUN COMPLETE";
        document.getElementById("run-complete-text").textContent = `${activeRun.name} cleared · Score ${score} · ${config.label}`;
        showPanel(runCompletePanel);
        playBeep(1320, .3, "triangle");
        return;
    }
    activeRun.index = nextIndex;
    currentLevel = nextIndex + 1;
    if (activeRun.kind === "story") localStorage.setItem("decguy_story_progress", String(nextIndex));
    const next = activeRun.levels[nextIndex];
    if (next.type === "boss") {
        completeTitle.textContent = "DECAY CORE DETECTED";
        completeTitle.style.color = "#ff4f55";
        nextLevelText.textContent = "Collect energy nodes, then ram the exposed core.";
    } else if (next.type === "challenge") {
        completeTitle.textContent = "BONUS CONTRACT";
        completeTitle.style.color = "#29e9ff";
        nextLevelText.textContent = `${next.name} LOADING...`;
    } else {
        completeTitle.textContent = reason || "LAYER DECRYPTED";
        completeTitle.style.color = "#66ff79";
        nextLevelText.textContent = `Loading maze ${currentLevel}: ${next.name}`;
    }
    completePanel.classList.remove("hidden");
    playBeep(880, .1, "sine");
    setTimeout(() => playBeep(1100, .15, "sine"), 120);
    setTimeout(() => playBeep(1320, .3, "triangle"), 240);
    setTimeout(startLevel, 2400);
}

function triggerGameOver() {
    gameOver = true;
    gameRunning = false;
    transitioning = false;
    tiltActive = false;
    cabinet.classList.remove("tilt-active");
    finalScoreText.textContent = `SCORE: ${score} · ${config.label} · ${activeEntry?.name || `LAYER ${currentLevel}`}`;
    if (score > highscore) {
        highscore = score;
        localStorage.setItem("decman_hi", highscore);
        hiScoreAlert.classList.remove("hidden");
    } else {
        hiScoreAlert.classList.add("hidden");
    }
    loadHighScore();
    gameoverPanel.classList.remove("hidden");
}

function draw() {
    ctx.fillStyle = "#020407";
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    drawMap();
    if (mode === "challenge" && challenge) drawChallengeItems();
    if (mode === "boss" && boss) drawBossStage();
    if (mode !== "boss") enemies.forEach(drawSpectre);
    drawPlayer();
    drawHud();
    if (challenge && challenge.hitFlash > 0) {
        ctx.fillStyle = `rgba(255,30,30,${challenge.hitFlash / 70})`;
        ctx.fillRect(0, 0, canvas.width, canvas.height);
    }
    if (tiltActive && Math.floor(Date.now() / 150) % 2 === 0) {
        ctx.fillStyle = "#ff2938";
        ctx.font = 'bold 36px "Courier New"';
        ctx.fillText("TILT", canvas.width / 2 - 45, canvas.height / 2);
    }
}

function drawMap() {
    const theme = mode === "boss"
        ? { wall: "#43141a", edge: "#ff4050", dot: "#fff" }
        : mode === "challenge"
            ? { wall: "#242044", edge: "#806bff", dot: "#fff" }
            : currentTheme;
    const powered = player.powerTimer > 0;

    for (let y = 0; y < ROWS; y++) {
        for (let x = 0; x < COLS; x++) {
            const tile = currentMap[y]?.[x];
            const px = x * TILE;
            const py = y * TILE;
            if (tile === WALL) {
                ctx.fillStyle = powered ? `hsl(${(Date.now() / 8 + x * 5) % 360} 55% 22%)` : theme.wall;
                ctx.fillRect(px, py, TILE, TILE);
                ctx.strokeStyle = powered ? "#fff" : theme.edge;
                ctx.strokeRect(px + 2, py + 2, TILE - 4, TILE - 4);
            } else if (tile === SPECTRE_HOME) {
                ctx.fillStyle = "#101625";
                ctx.fillRect(px, py, TILE, TILE);
                ctx.strokeStyle = "#38466c";
                ctx.strokeRect(px + 2, py + 2, TILE - 4, TILE - 4);
            } else if (tile === SPECTRE_GATE) {
                ctx.fillStyle = "#ff67d8";
                ctx.fillRect(px, py + 6, TILE, 4);
            } else if (tile === DOT) {
                ctx.fillStyle = theme.dot;
                ctx.fillRect(px + 6, py + 6, 4, 4);
            } else if (tile === POWER) {
                ctx.save();
                ctx.translate(px + 8, py + 8);
                ctx.rotate(Date.now() / 220);
                ctx.fillStyle = "#ffd43b";
                ctx.fillRect(-6, -6, 12, 12);
                ctx.fillStyle = "#6b4d00";
                ctx.font = "bold 8px monospace";
                ctx.fillText("¢", -3, 3);
                ctx.restore();
            }
        }
    }
}

function drawPlayer() {
    if (player.invulnerable > 0 && Math.floor(player.invulnerable / 6) % 2 === 0) return;
    const centerX = player.x + 8;
    const centerY = player.y + 8;
    ctx.save();
    ctx.translate(centerX, centerY);
    const angle = Math.atan2(player.dirY, player.dirX || 1);
    ctx.rotate(angle);
    ctx.fillStyle = player.powerTimer > 0 ? "#fff5a0" : "#f4d52c";
    ctx.beginPath();
    ctx.arc(0, 0, 7.4, 0, Math.PI * 2);
    ctx.fill();
    ctx.strokeStyle = "#8e7211";
    ctx.lineWidth = 1.5;
    ctx.stroke();
    ctx.fillStyle = "#121212";
    ctx.fillRect(1, -4, 3, 2);
    ctx.beginPath();
    ctx.moveTo(4, 1);
    ctx.lineTo(7, 2.5);
    ctx.lineTo(4, 4);
    ctx.closePath();
    ctx.fill();
    ctx.restore();
}

function drawSpectre(enemy) {
    if (enemy.releaseTimer > 0 && Math.floor(enemy.releaseTimer / 8) % 2 === 0) return;
    const frightened = player.powerTimer > 0 && mode === "normal";
    ctx.save();
    ctx.translate(enemy.x + 8, enemy.y + 8);
    ctx.fillStyle = frightened ? "#3355cc" : enemy.color;
    ctx.beginPath();
    ctx.moveTo(0, -8);
    ctx.lineTo(7, -3);
    ctx.lineTo(6, 5);
    ctx.lineTo(2, 8);
    ctx.lineTo(0, 4);
    ctx.lineTo(-3, 8);
    ctx.lineTo(-7, 4);
    ctx.lineTo(-6, -3);
    ctx.closePath();
    ctx.fill();
    ctx.strokeStyle = frightened ? "#8fa4ff" : "#ffffff88";
    ctx.stroke();
    ctx.fillStyle = "#071019";
    ctx.fillRect(-3, -3, 2, 3);
    ctx.fillRect(2, -3, 2, 3);
    ctx.restore();
}

function drawChallengeItems() {
    challenge.items.forEach(item => {
        if (item.collected) return;
        const x = item.x * TILE + 8;
        const y = item.y * TILE + 8;
        const active = challenge.type !== "SIGNAL CHAIN" || item.order === challenge.collected;
        ctx.save();
        ctx.translate(x, y);
        ctx.globalAlpha = active ? 1 : .28;
        ctx.rotate(Date.now() / 260 + item.order);
        ctx.fillStyle = challenge.type === "DRONE HEIST" ? "#ff785a" : "#ffe348";
        ctx.fillRect(-6, -6, 12, 12);
        ctx.restore();
        ctx.fillStyle = "#101010";
        ctx.font = "bold 8px monospace";
        const symbol = challenge.type === "SIGNAL CHAIN" ? String(item.order + 1) : challenge.type === "DRONE HEIST" ? "L" : "¢";
        ctx.fillText(symbol, x - 3, y + 3);
    });
}

function drawBossStage() {
    boss.nodes.forEach(node => {
        if (node.collected || !boss.shield) return;
        const pulse = 4 + Math.sin(Date.now() / 100) * 2;
        ctx.strokeStyle = "#3fffea";
        ctx.lineWidth = 2;
        ctx.beginPath();
        ctx.arc(node.x * TILE + 8, node.y * TILE + 8, pulse, 0, Math.PI * 2);
        ctx.stroke();
        ctx.fillStyle = "#d8ffff";
        ctx.fillRect(node.x * TILE + 6, node.y * TILE + 6, 4, 4);
    });

    boss.projectiles.forEach(projectile => {
        if (projectile.warning > 0) {
            ctx.save();
            ctx.globalAlpha = .25 + Math.sin(Date.now() / 60) * .2;
            ctx.strokeStyle = "#ff4255";
            ctx.setLineDash([5, 5]);
            ctx.beginPath();
            ctx.moveTo(projectile.x, projectile.y);
            ctx.lineTo(projectile.targetX, projectile.targetY);
            ctx.stroke();
            ctx.restore();
        } else {
            ctx.fillStyle = "#ff3048";
            ctx.beginPath();
            ctx.arc(projectile.x, projectile.y, 4, 0, Math.PI * 2);
            ctx.fill();
        }
    });

    ctx.save();
    ctx.translate(boss.x + 8, boss.y + 8);
    ctx.rotate(Date.now() / 700);
    ctx.fillStyle = boss.shield ? "#d63246" : "#fff4b3";
    ctx.beginPath();
    for (let side = 0; side < 6; side++) {
        const angle = side * Math.PI / 3;
        const x = Math.cos(angle) * 12;
        const y = Math.sin(angle) * 12;
        if (side === 0) ctx.moveTo(x, y);
        else ctx.lineTo(x, y);
    }
    ctx.closePath();
    ctx.fill();
    ctx.strokeStyle = boss.shield ? "#ff8794" : "#fff";
    ctx.lineWidth = 2;
    ctx.stroke();
    ctx.rotate(-Date.now() / 350);
    ctx.fillStyle = "#111";
    ctx.fillRect(-4, -4, 8, 8);
    ctx.restore();

    if (boss.shield) {
        ctx.strokeStyle = "#ff3a69";
        ctx.beginPath();
        ctx.arc(boss.x + 8, boss.y + 8, 17 + Math.sin(Date.now() / 120) * 2, 0, Math.PI * 2);
        ctx.stroke();
    }
}

function drawHud() {
    ctx.fillStyle = "#02060de8";
    ctx.fillRect(0, 0, canvas.width, 28);
    ctx.fillRect(0, canvas.height - 22, canvas.width, 22);
    ctx.font = 'bold 11px "Courier New", monospace';
    ctx.fillStyle = "#fff";
    ctx.fillText(`SCORE ${String(score).padStart(6, "0")}`, 10, 18);
    ctx.fillText(`SHIELDS ${player.lives}`, 337, 18);

    let centerText = `L${currentLevel} ${currentMazeName}`;
    let footer = `${config.label} · ${pelletsEaten}/${totalPellets} CACHE`;
    if (mode === "challenge" && challenge) {
        centerText = `${challenge.type} ${Math.ceil(challenge.time / 60)}s`;
        footer = `${challenge.collected}/${challenge.required} · CONTACT COSTS 3 SECONDS`;
    }
    if (mode === "boss" && boss) {
        centerText = `CORE HP ${boss.hp}/${boss.maxHp}`;
        footer = boss.shield
            ? `ENERGY NODES ${boss.nodesCollected}/${boss.nodesNeeded}`
            : `SHIELD DOWN — RAM THE CORE! ${Math.ceil(boss.vulnerableTimer / 60)}s`;
    }
    ctx.fillStyle = mode === "boss" ? "#ff6b76" : mode === "challenge" ? "#59edff" : currentTheme.edge;
    ctx.textAlign = "center";
    ctx.fillText(centerText, canvas.width / 2, 18);
    ctx.fillStyle = "#d9e4ef";
    ctx.fillText(footer, canvas.width / 2, canvas.height - 7);
    ctx.textAlign = "left";
}

